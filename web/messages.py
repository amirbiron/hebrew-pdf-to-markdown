def legend() -> list[dict]:
    """ההחלטות לפי הסדר, לסיכום ולמקרא בדף: הקוד (conversion.DECISION_CODES), השם (מהציון עצמו) וההסבר."""
    return [{"decision": conversion.DECISION_CODES[name], "text": name, "help": DECISIONS[name]}
            for name in score.DECISIONS]


def explained(result: dict) -> dict:
    """התוצאה של ההמרה (conversion.payload), עם ההסבר של כל סיבה והערה ועם המקרא. מחזירה מבנה חדש."""
    pages = [{**page,
              "reasons": [{**reason, "help": REASONS[reason["kind"]]} for reason in page["reasons"]],
              "notes": [{**note, "help": NOTES[note["kind"]]} for note in page["notes"]]}
             for page in result["pages"]]
    return {**result, "pages": pages, "legend": legend()}
